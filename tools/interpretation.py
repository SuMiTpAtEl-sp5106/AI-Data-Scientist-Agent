import os
import pickle
import pandas as pd
import numpy as np

def generate_executive_report(model_path: str, processed_path: str, output_path: str = "storage/reports/executive_summary.md") -> dict:
   
    report_content = "# 📊 Autonomous Data Scientist: Executive Summary Report\n\n**Execution Status:** Completed Successfully"
    
    if not os.path.exists(model_path) or not os.path.exists(processed_path):
        raise FileNotFoundError("Model or processed data artifacts missing. Ensure preprocessing and training steps are completed.")

    with open(model_path, "rb") as f:
        model = pickle.load(f)

    with open(processed_path, "rb") as f:
        data = pickle.load(f)
        
    feature_names = data.get("feature_names", [])
    os.makedirs(os.path.dirname(output_path), exist_ok=True)

    top_drivers_text = ""
    
  
    if hasattr(model, "coef_"):
  
        coefficients = model.coef_[0] if hasattr(model.coef_, "__len__") and len(model.coef_.shape) > 1 else model.coef_
        
        if len(coefficients) == len(feature_names):
            coef_df = pd.DataFrame({"Feature": feature_names, "Importance": coefficients})
            top_positive = coef_df.sort_values(by="Importance", ascending=False).head(5)
            top_negative = coef_df.sort_values(by="Importance", ascending=True).head(5)

            top_drivers_text = "### 🔍 Key Feature Drivers (Model Coefficients)\n\n"
            top_drivers_text += "**Top Factors Increasing Target Value / Risk:**\n"
            for _, row in top_positive.iterrows():
                top_drivers_text += f"- **{row['Feature']}**: {row['Importance']:+.4f}\n"

            top_drivers_text += "\n**Top Factors Decreasing Target Value / Risk:**\n"
            for _, row in top_negative.iterrows():
                top_drivers_text += f"- **{row['Feature']}**: {row['Importance']:+.4f}\n"

   
    elif hasattr(model, "feature_importances_"):
        importances = model.feature_importances_
        if len(importances) == len(feature_names):
            imp_df = pd.DataFrame({"Feature": feature_names, "Importance": importances})
            top_features = imp_df.sort_values(by="Importance", ascending=False).head(10)

            top_drivers_text = "### 🌲 Key Feature Drivers (Tree Feature Importances)\n\n"
            top_drivers_text += "**Top Influential Features:**\n"
            for _, row in top_features.iterrows():
                top_drivers_text += f"- **{row['Feature']}**: {row['Importance']:.4f}\n"

    model_name = type(model).__name__

    report_content = f"""# 📊 Autonomous Data Scientist: Executive Summary Report
**Execution Status:** Completed Successfully  
**Champion Model:** {model_name} (Optimized via GridSearchCV)  

---

## 🚀 1. Pipeline Execution Overview
- **Data Ingestion & Cleaning:** Handled missing values, formatted types, and cleaned dataset.
- **Exploratory Data Analysis (EDA):** Generated distribution charts, correlation heatmaps, and feature interaction plots (`storage/plots/`).
- **Feature Engineering:** One-hot encoded multi-class variables, scaled numerical attributes, created domain interaction ratios, and performed train-test splits.

---

## 🏆 2. Model Performance Summary
The champion model was selected based on robust cross-validation and test set evaluation:
- **Model Type:** {model_name}
- **Optimization Strategy:** GridSearchCV with 3-fold cross-validation

---

{top_drivers_text}

---
*Report automatically generated by your LangGraph Autonomous Data Scientist Agent.*
"""

    with open(output_path, "w", encoding="utf-8") as f:
        f.write(report_content)

    print(f"[✓] Log: Executive Summary generated successfully at {output_path}")

    return {
        "report_path": output_path,
        "features_analyzed": len(feature_names)
    }